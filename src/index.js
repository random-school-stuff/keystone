import { existsSync } from "node:fs";
import { createServer } from "node:http";
import { hostname } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import express from "express";
import { server as wisp } from "@mercuryworkshop/wisp-js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");

/* -------------------------------------------------------------------------
   Sanity check: the browser bundles are generated by `npm run build`.
   ------------------------------------------------------------------------- */

const requiredAssets = [
	"uv/uv.bundle.js",
	"uv/uv.sw.js",
	"uv/uv.config.js",
	"baremux/index.js",
	"epoxy/index.mjs",
];

const missing = requiredAssets.filter((file) => !existsSync(join(publicDir, file)));
if (missing.length > 0) {
	console.error("Missing browser bundles:");
	for (const file of missing) console.error(`  public/${file}`);
	console.error("\nRun `npm run build` first, then start the server again.");
	process.exit(1);
}

/* -------------------------------------------------------------------------
   Wisp tuning
   ------------------------------------------------------------------------- */

/** Proxies allowed to report the real client IP through forwarded headers. */
const trustedProxies = (process.env.TRUSTED_PROXIES ?? "127.0.0.1,::1")
	.split(",")
	.map((value) => value.trim())
	.filter(Boolean);

// Keystone is a public endpoint, so refuse anything that could reach the
// server's own network, and cap concurrency per client.
wisp.options.allow_private_ips = false;
wisp.options.allow_loopback_ips = false;
wisp.options.allow_direct_ip = true;
wisp.options.stream_limit_total = Number(process.env.WISP_STREAM_LIMIT ?? 200);
wisp.options.stream_limit_per_host = 50;
wisp.options.parse_real_ip = true;
wisp.options.parse_real_ip_from = trustedProxies;
wisp.options.wisp_motd = "Keystone";

/* -------------------------------------------------------------------------
   HTTP
   ------------------------------------------------------------------------- */

const app = express();
app.disable("x-powered-by");

app.use((req, res, next) => {
	res.setHeader("X-Content-Type-Options", "nosniff");
	res.setHeader("Referrer-Policy", "no-referrer");
	next();
});

app.get("/healthz", (req, res) => {
	res.json({ ok: true, uptime: Math.round(process.uptime()) });
});

app.use(
	express.static(publicDir, {
		index: "index.html",
		extensions: ["html"],
		setHeaders(res, path) {
			// Never cache the shell; do cache the immutable vendor bundles.
			if (path.endsWith(".html")) {
				res.setHeader("Cache-Control", "no-cache");
			} else if (/\/(uv|baremux|epoxy)\//.test(path)) {
				res.setHeader("Cache-Control", "public, max-age=86400");
			}
		},
	}),
);

app.use((req, res) => {
	res.status(404).sendFile(join(publicDir, "404.html"));
});

const server = createServer(app);

server.on("upgrade", (req, socket, head) => {
	let pathname;
	try {
		pathname = new URL(req.url ?? "/", "http://localhost").pathname;
	} catch {
		socket.destroy();
		return;
	}

	if (pathname === "/wisp/" || pathname === "/wisp") {
		wisp.routeRequest(req, socket, head);
		return;
	}

	socket.destroy();
});

const port = Number(process.env.PORT ?? 8080);
const host = process.env.HOST ?? "0.0.0.0";

server.on("listening", () => {
	console.log("Keystone is running:");
	console.log(`  http://localhost:${port}`);
	if (host === "0.0.0.0") console.log(`  http://${hostname()}:${port}`);
	console.log(`  Wisp endpoint: ws://<host>:${port}/wisp/`);
});

function shutdown(signal) {
	console.log(`\n${signal} received, shutting down.`);
	server.close(() => process.exit(0));

	// Don't hang forever on open proxy streams.
	setTimeout(() => process.exit(0), 5000).unref();
}

process.on("SIGINT", () => shutdown("SIGINT"));
process.on("SIGTERM", () => shutdown("SIGTERM"));

server.listen({ port, host });
